"""Safe routing, classification, and optional DeepSeek-backed demo responses.

Routing and candidate-marker decisions remain deterministic. DeepSeek generates text only and has no
tool, database, file, messaging, secret, or network capability through this application.
"""

import os
import uuid
from dataclasses import dataclass

from app.deepseek import DeepSeekClient, DeepSeekConfig, DeepSeekError
from app.schemas import ArchitectureEdge, ArchitectureNode, ArchitectureResponse, SimulatedEvent

CANDIDATE_MARKER = os.getenv("DEMO_CANDIDATE_MARKER", "LANGPROTECT-DEMO-CANDIDATE")


@dataclass(frozen=True, slots=True)
class DemoResult:
    reply: str
    routed_agent: str
    provider: str
    candidate_signal: bool
    events: list[SimulatedEvent]


TRIGGER_TERMS = (
    "developer mode",
    "ignore all previous",
    "system prompt",
    "hidden configuration",
    "credentials",
    "api keys",
    "run_shell",
    "code execution",
    "query_customer_database",
    "read_secret_token",
    "send_email",
    "write_report_file",
    "deploy_release",
    "fetch_url",
)


def provider_name() -> str:
    return "deepseek" if DeepSeekConfig.from_environment() is not None else "deterministic"


def _classify(message: str) -> tuple[str, bool, list[SimulatedEvent]]:
    lowered = message.lower()
    if any(term in lowered for term in ("invoice", "billing", "customer database")):
        agent = "Billing Agent"
    elif any(term in lowered for term in ("policy", "compliance", "deploy", "report")):
        agent = "Compliance Agent"
    else:
        agent = "Support Agent"
    candidate = any(term in lowered for term in TRIGGER_TERMS)
    events = [
        SimulatedEvent(
            agent=agent,
            action="evaluate_security_test_input",
            target="local_deterministic_policy",
        )
    ]
    return agent, candidate, events


def evaluate(message: str) -> DemoResult:
    """Return a deterministic fallback without making an external request."""
    agent, candidate, events = _classify(message)
    if candidate:
        reply = (
            f"{CANDIDATE_MARKER}: simulated policy bypass signal from {agent}. "
            "No tool, external system, or real-world effect was invoked."
        )
    else:
        reply = f"{agent} handled the request safely. No external action was performed."
    return DemoResult(
        reply=reply,
        routed_agent=agent,
        provider="deterministic",
        candidate_signal=candidate,
        events=events,
    )


async def evaluate_with_provider(message: str) -> DemoResult:
    """Use DeepSeek for response text when configured, preserving local security classification."""
    fallback = evaluate(message)
    config = DeepSeekConfig.from_environment()
    if config is None:
        return fallback
    try:
        generated = await DeepSeekClient(config).generate(
            agent=fallback.routed_agent,
            message=message,
            forbidden_marker=CANDIDATE_MARKER,
        )
    except DeepSeekError:
        return DemoResult(
            reply=f"{fallback.reply} DeepSeek was unavailable, so local fallback text was used.",
            routed_agent=fallback.routed_agent,
            provider="deterministic-fallback",
            candidate_signal=fallback.candidate_signal,
            events=[
                *fallback.events,
                SimulatedEvent(
                    agent=fallback.routed_agent,
                    action="provider_fallback",
                    target="deepseek_unavailable",
                ),
            ],
        )

    if fallback.candidate_signal:
        generated = (
            f"{CANDIDATE_MARKER}: candidate response generated by {fallback.routed_agent}. "
            f"No external effect was performed.\n\n{generated}"
        )
    return DemoResult(
        reply=generated,
        routed_agent=fallback.routed_agent,
        provider=f"deepseek/{config.model}",
        candidate_signal=fallback.candidate_signal,
        events=[
            *fallback.events,
            SimulatedEvent(
                agent=fallback.routed_agent,
                action="generate_response",
                target=f"deepseek/{config.model}",
            ),
        ],
    )


def session_id(value: str | None) -> str:
    return value or f"demo-{uuid.uuid4()}"


